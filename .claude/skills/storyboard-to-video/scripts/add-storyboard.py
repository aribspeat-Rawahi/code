"""Validate a storyboard JSON and install it into a project (src/storyboards/<id>.json),
then regenerate src/storyboards/index.ts so Remotion shows "<id>" and "<id>-landscape".

Usage: python3 add-storyboard.py <project-dir> <storyboard.json>
"""
import json
import re
import sys
from pathlib import Path

KINDS = {"thought", "speech", "tag", "sign"}


def fail(msg):
    sys.exit(f"Error: {msg}")


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    project, src = Path(sys.argv[1]), Path(sys.argv[2])
    sb = json.loads(src.read_text(encoding="utf-8"))
    public = project / "public"

    if not re.fullmatch(r"[a-z0-9-]+", sb.get("id", "")):
        fail('"id" must use only a-z, 0-9 and "-" (it becomes the composition name)')
    for key in ("lang", "brand", "intro", "outro", "scenes"):
        if key not in sb:
            fail(f'missing "{key}"')
    for key in ("logo", "dark", "mid", "accent", "light"):
        if key not in sb["brand"]:
            fail(f'brand is missing "{key}"')

    files = [sb["brand"]["logo"]] + [v for v in (sb.get("cover") or {}).values() if v]
    warnings = []
    for i, s in enumerate(sb["scenes"], start=1):
        for key in ("image", "title", "voiceover"):
            if not s.get(key):
                fail(f'scene {i} is missing "{key}"')
        files.append(s["image"])
        for l in s.get("labels", []):
            if l.get("kind") not in KINDS:
                fail(f"scene {i}: label kind must be one of {sorted(KINDS)}")
            if not (0 <= l.get("x", -1) <= 1 and 0 <= l.get("y", -1) <= 1):
                fail(f'scene {i}: label "{l.get("text")}" needs x and y between 0 and 1')
        if not s.get("captions"):
            warnings.append(f"scene {i} has no voiceover yet (run a voiceover script); it will be 9 s and silent")
    for f in files:
        if not (public / f).is_file():
            fail(f"file not found in public/: {f}")

    out_dir = project / "src" / "storyboards"
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / f"{sb['id']}.json").write_text(json.dumps(sb, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    write_index(out_dir)
    for w in warnings:
        print("Warning:", w)
    print(f"Installed storyboard '{sb['id']}' ({len(sb['scenes'])} scenes) → compositions {sb['id']} and {sb['id']}-landscape")


def write_index(out_dir):
    jsons = sorted(p for p in out_dir.glob("*.json"))
    lines = ["// Generated by scripts/add-storyboard.py — do not edit by hand.", 'import type { Storyboard } from "../types";']
    names = []
    for n, p in enumerate(jsons):
        lines.append(f'import s{n} from "./{p.name}";')
        names.append(f"s{n}")
    lines.append(f"\nexport const STORYBOARDS = [{', '.join(names)}] as unknown as Storyboard[];\n")
    (out_dir / "index.ts").write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
